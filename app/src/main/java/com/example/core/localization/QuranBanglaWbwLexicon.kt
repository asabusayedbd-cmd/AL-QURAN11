    fun lookup(textUthmani: String, englishMeaning: String = ""): String? {
        val norm = BidiUtils.normalizeArabicForSearch(textUthmani)
        if (norm.isNotBlank()) {
            EXACT_NORMALIZED_BN[norm]?.let { return it }
        }
        val cleanEn = englishMeaning.trim().lowercase()
        if (cleanEn.isNotBlank()) {
            EN_FALLBACK_GLOSSES[cleanEn]?.let { return it }
        }
        return null
    }
